export type TranslationKey = keyof typeof translations['fr'];

export function getT(lang: Lang) {
  return (key: TranslationKey): string => translations[lang][key] ?? translations.fr[key];
}

// Map filter option values to translated strings
export function translateOption(lang: Lang, value: string): string {
  const t = getT(lang);
  const map: Record<string, TranslationKey> = {
    'Toutes': 'optAll',
    'Manuelle': 'optManual',
    'Automatique / PDK': 'optAuto',
    'Essence': 'optPetrol',
    'Hybride': 'optHybrid',
    'Électrique': 'optElectric',
    'Professionnel': 'optPro',
    'Particulier': 'optPrivate',
    'Tous': 'optAllSellers',
    'Moins de 24h': 'opt24h',
    'Moins de 7 jours': 'opt7d',
    'Moins de 30 jours': 'opt30d',
    '3 étoiles et +': 'opt3stars',
    '4 étoiles et +': 'opt4stars',
    '4.5 étoiles et +': 'opt45stars',
    'Europe Globale': 'cEurope',
    'Allemagne': 'cGermany',
    'France': 'cFrance',
    'Italie': 'cItaly',
    'Espagne': 'cSpain',
    'Belgique': 'cBelgium',
    'Pays-Bas': 'cNetherlands',
    'Suisse': 'cSwitzerland',
    'Autriche': 'cAustria',
    'Portugal': 'cPortugal',
    'Luxembourg': 'cLuxembourg',
  };
  const key = map[value];
  return key ? t(key) : value;
}
